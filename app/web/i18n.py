def resolve_locale(value: object) -> str:
    return value if isinstance(value, str) and value in SUPPORTED_LOCALES else "ru"


def copy_for(locale: str) -> Mapping[str, str]:
    return _COPY[resolve_locale(locale)]


def text(locale: str, key: str, **values: Any) -> str:
    return _COPY[resolve_locale(locale)][key].format(**values)


def option_label(locale: str, group: str, value: str) -> str:
    locale = resolve_locale(locale)
    return _OPTIONS[group].get(locale, {}).get(value, value)


def option_list(locale: str, group: str, values: tuple[str, ...]) -> list[dict[str, str]]:
    return [{"value": value, "label": option_label(locale, group, value)} for value in values]


def locale_options(active: str) -> list[dict[str, object]]:
    return [
        {"code": code, "label": LOCALE_LABELS[code], "active": code == active}
        for code in SUPPORTED_LOCALES
    ]
